# c_backend.py -- генератор ANF -> C99 для SCore.
# Внимание: замыкания генерируются как заглушки (fn = NULL); полноценная
# генерация функций замыканий -- повестка v0.4. См. RELEASE_v0.3.md.
import json
import re

def sanitize(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]", "_", name)
    if not s[0].isalpha() and s[0] != "_":
        s = "_" + s
    return s

def emit_vec(data, env):
    arr_name = sanitize("vec_" + str(id(data)))
    lines = []
    lines.append("double %s[] = {" % arr_name)
    for x in data:
        lines.append("    %s," % x)
    lines.append("};")
    return lines, "make_vec(%s, %d)" % (arr_name, len(data))

def emit_term(term, name, env_stack):
    """term: ("let", name, body, next) | ("var", n) | ("app", f, x) |
       ("if", c, t, e) | ("fun", params, body) | ("vec", elems) |
       ("int", x) | ("float", x) | ("bool", b)"""
    lines = []
    tag = term[0]
    if tag == "int":
        return lines, "make_int(%d)" % term[1]
    if tag == "float":
        return lines, "make_float(%s)" % term[1]
    if tag == "bool":
        return lines, "make_bool(%d)" % (1 if term[1] else 0)
    if tag == "vec":
        vec_lines, vec_expr = emit_vec(term[1], env_stack)
        lines += vec_lines
        return lines, vec_expr
    if tag == "var":
        return lines, 'env_get(env, "%s")' % term[1]
    if tag == "app":
        f_lines, f_expr = emit_term(term[1], None, env_stack)
        x_lines, x_expr = emit_term(term[2], None, env_stack)
        lines += f_lines + x_lines
        return lines, "rt_apply(%s, %s)" % (f_expr, x_expr)
    if tag == "if":
        c_lines, c_expr = emit_term(term[1], None, env_stack)
        t_lines, t_expr = emit_term(term[2], None, env_stack)
        e_lines, e_expr = emit_term(term[3], None, env_stack)
        lines += c_lines + t_lines + e_lines
        return lines, "rt_select(%s, %s, %s)" % (c_expr, t_expr, e_expr)
    if tag == "let":
        name_, body, nxt = term[1], term[2], term[3]
        name_san = sanitize(name_)
        body_lines, body_expr = emit_term(body, None, env_stack + [name_])
        nxt_lines, nxt_expr = emit_term(nxt, None, env_stack + [name_])
        lines.append("Value val_%s = %s;" % (name_san, body_expr))
        lines.append('trace_bind("%s", val_%s);' % (name_, name_san))
        lines.append('EnvNode *env_%s = env_cons("%s", val_%s, env);' % (name_san, name_, name_san))
        lines += nxt_lines
        return lines, nxt_expr
    if tag == "fun":
        params, body = term[1], term[2]
        lines.append("/* Замыкание: params=%s (заглушка, см. RELEASE_v0.3.md) */" % params)
        lines.append("Closure clo_%s = { .env = env, .fn = NULL };" % sanitize(str(id(body))))
        return lines, "make_closure(&clo_%s)" % sanitize(str(id(body)))
    raise ValueError("Unknown AST node: %s" % tag)

def generate_all_terms(terms):
    c_lines = ['#include "sound_rt.h"', "", "/* Autogenerated. Do not edit. */", ""]
    manifest = {}
    for name, term in terms.items():
        c_lines.append("Value term_%s(void) {" % name)
        c_lines.append("    EnvNode *env = NULL;")
        body_lines, result_expr = emit_term(term, None, [])
        c_lines += body_lines
        c_lines.append("    Value res = %s;" % result_expr)
        c_lines.append("    trace_result(res);")
        c_lines.append("    return res;")
        c_lines.append("}")
        c_lines.append("")
        manifest[name] = {"func": "term_%s" % name, "type": "dynamic", "expected_canon": None}
    return "\n".join(c_lines), manifest

if __name__ == "__main__":
    # Терм T06 (лексический захват). Полный корпус T07-T17 -- по мере расширения.
    terms = {
        "T06": ("let", "x1", ("int", 1),
                ("let", "f", ("fun", ["y"],
                              ("app", ("var", "x1"), ("var", "y"))),
                 ("let", "x1", ("int", 105),
                  ("app", ("var", "f"), ("int", 5)))))
    }
    code, manifest = generate_all_terms(terms)
    with open("all_terms.c", "w") as f:
        f.write(code)
    with open("manifest.json", "w") as f:
        json.dump(manifest, f, indent=2)
    print("generated all_terms.c + manifest.json")
